merge_keys = ['State_UT_Code', 'District_Code',
    'FSU',             # First Stage Unit
    'Sector',          # Rural/Urban
    'Sample_Sg_Sb_No',    # Hamlet Group / Sub-block
    'Second_Stage_Stratum_No',             # Second Stage Stratum
    'Sample_Household_Number'     # Household Number
]

hh_cols = merge_keys + ['Social_Group', 'Household_Size']
per_cols = merge_keys + [
    'Person_Serial_No', 'Age', 'General_Education_Level',
    'Principal_Status_Code', 'Principal_Enterprise_Type',
    'Principal_Job_Contract_Type', 'CWS_Earnings_Salaried', 'CWS_Earnings_SelfEmployed', 'Principal_Industry_Code'
]

hh_data = pd.read_csv('/content/drive/MyDrive/mani-python-rm/chhv1.csv', usecols=hh_cols)
per_data = pd.read_csv('/content/drive/MyDrive/mani-python-rm/cperv1.csv', usecols=per_cols)

df = pd.merge(per_data, hh_data, on=merge_keys, how='inner')

df['Age_Sq'] = df['Age'] ** 2

df['Urban_Dummy'] = np.where(df['Sector'] == 2, 1, 0)

conditions_edu = [
    (df['General_Education_Level'] <= 5),              # Below Secondary (Our Baseline)
    (df['General_Education_Level'].isin([6, 7, 8])),   # Secondary / Higher Sec / Diploma
    (df['General_Education_Level'] == 10),             # Graduate (Bachelor's)
    (df['General_Education_Level'] >= 11)              # Postgraduate & Above
]
choices_edu = ['Below_Secondary', 'Secondary_Plus', 'Graduate', 'PostGraduate']
df['Edu_Category'] = np.select(conditions_edu, choices_edu, default='Below_Secondary')

edu_dummies = pd.get_dummies(df['Edu_Category'], drop_first=True, dtype=int)
df = pd.concat([df, edu_dummies], axis=1)

df['nic_2digit_derived'] = df['Principal_Industry_Code'] // 1000


conditions_ind = [
    (df['nic_2digit_derived'] <= 3),      # Agriculture/Primary Sector (Our Baseline)
    (df['nic_2digit_derived'].between(4, 43)),  # Manufacturing/Construction (Secondary)
    (df['nic_2digit_derived'] > 43)       # Services/IT/Retail (Tertiary)
]
choices_ind = ['Primary', 'Secondary', 'Tertiary']
df['Ind_Category'] = np.select(conditions_ind, choices_ind, default='Primary')

ind_dummies = pd.get_dummies(df['Ind_Category'], drop_first=True, dtype=int)
df = pd.concat([df, ind_dummies], axis=1)

df = df[(df['Age'] >= 15) & (df['Age'] <= 65)]
df = df[df['Principal_Status_Code'] == 31]

df['Category_Dummy'] = np.where(df['Social_Group'].isin([1, 2, 3]), 1, 0)

public_codes = [1, 2, 3]
df['Sector_Dummy'] = np.where(df['Principal_Enterprise_Type'].isin(public_codes), 0, 1)

df['Interaction_Term'] = df['Category_Dummy'] * df['Sector_Dummy']

df = df.dropna(subset=['CWS_Earnings_Salaried'])
df = df[df['CWS_Earnings_Salaried'] > 0]
df['Log_Wage'] = np.log(df['CWS_Earnings_Salaried'])

edu_mapping = {
    1: 0,   # Not literate
    2: 0,   # Literate without formal schooling
    3: 5,   # Below primary
    4: 5,   # Primary
    5: 8,   # Middle
    6: 10,  # Secondary
    7: 12,  # Higher secondary
    8: 15,  # Diploma/Certificate
    10: 15, # Graduate
    11: 17  # Postgraduate and above
}

df['Edu_Years'] = df['General_Education_Level'].map(edu_mapping)

print(df[['Log_Wage', 'Category_Dummy', 'Sector_Dummy', 'Interaction_Term', 'Edu_Years']].head())



df.to_excel('df_output.xlsx', index=False)

